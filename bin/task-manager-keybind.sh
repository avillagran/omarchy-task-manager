#!/usr/bin/env bash
# Manage the SUPER+SHIFT+T keybind that toggles the Task Manager popup.
#
# The bind is OPT-IN (Omarchy marketplace rule: never overwrite user config
# without explicit consent). The plugin card's keyboard toggle calls this
# script; install.sh never enables it. Writes are mktemp+mv in the same
# directory, and Hyprland auto-reloads lua on write — an explicit
# `hyprctl reload` would race the watcher, so it is never called.
set -euo pipefail

LUA_DIR="$HOME/.config/hypr"
LUA_FILE="$LUA_DIR/task-manager-bindings.lua"
HL="$LUA_DIR/hyprland.lua"
REQUIRE='require("hypr.task-manager-bindings")'

enabled() {
  [ -f "$LUA_FILE" ] && [ -f "$HL" ] && grep -qF "$REQUIRE" "$HL"
}

enable() {
  [ -f "$HL" ] || { echo "hyprland.lua not found" >&2; exit 1; }
  local tmp
  tmp="$(mktemp -p "$LUA_DIR" tm-bind.XXXXXX)"
  cat > "$tmp" <<'EOF'
-- Auto-generated by omarchy-task-manager (bin/task-manager-keybind.sh).
-- Binds SUPER+SHIFT+T to toggle the Task Manager popup. Disable it from the
-- Task Manager card (keyboard icon), or delete this file plus the
-- require("hypr.task-manager-bindings") line in hyprland.lua.
hl.unbind("SUPER + SHIFT + T")
o.bind("SUPER + SHIFT + T", "Task Manager", "omarchy-shell shell toggle io.github.avillagran.omarchy-task-manager")
EOF
  mv -f "$tmp" "$LUA_FILE"
  grep -qF "$REQUIRE" "$HL" || printf '\n%s\n' "$REQUIRE" >> "$HL"
  echo "enabled"
}

disable() {
  rm -f "$LUA_FILE"
  if [ -f "$HL" ] && grep -qF "$REQUIRE" "$HL"; then
    local tmp
    tmp="$(mktemp -p "$LUA_DIR" tm-hl.XXXXXX)"
    grep -vF "$REQUIRE" "$HL" > "$tmp" || true
    mv -f "$tmp" "$HL"
  fi
  echo "disabled"
}

case "${1:-status}" in
  enable)  enable ;;
  disable) disable ;;
  toggle)  if enabled; then disable; else enable; fi ;;
  status)  if enabled; then echo "enabled"; else echo "disabled"; fi ;;
  *) echo "usage: $0 {enable|disable|toggle|status}" >&2; exit 1 ;;
esac
